import {
  generatePuzzleWithAnalysis as generateG1,
  type GenerateOptions as LegacyGenerateOptions,
  type GeneratedPuzzle,
} from "./generator-g1";
import { generateG2 } from "./generator-g2";
import { generateG3, generateG4 } from "./generator-g3";
import type { Puzzle } from "./model";

export type { GeneratedPuzzle } from "./generator-g1";
export interface GenerateOptions extends LegacyGenerateOptions {
  readonly version?: string;
  /** g1 and g2 only. Later versions take every limit from the version itself,
   * so that a seed code alone decides the board. */
  readonly maxAttempts?: number;
}

/** The versions of ordinary 8×8 boards. The 10×10 daily and super versions
 * are not listed: they have their own seed codes and rankings. */
const GENERATORS: Readonly<
  Record<string, (options: GenerateOptions) => GeneratedPuzzle>
> = { g1: generateG1, g2: generateG2, g3: generateG3, g4: generateG4 };

export const GENERATOR_VERSIONS: readonly string[] = Object.keys(GENERATORS);

/** New boards use this version. Older versions stay reproducible because
 * shared links, histories and rankings identify boards generated by them. */
export const GENERATOR_VERSION = "g4";

export function isSupportedGeneratorVersion(version: string): boolean {
  return Object.hasOwn(GENERATORS, version);
}

export function generatePuzzleWithAnalysis(
  options: GenerateOptions = {},
): GeneratedPuzzle {
  const version = options.version ?? GENERATOR_VERSION;
  if (!isSupportedGeneratorVersion(version))
    throw new Error(`Unsupported generator version: ${version}`);
  return GENERATORS[version](options);
}

export function generatePuzzle(options: GenerateOptions = {}): Puzzle {
  return generatePuzzleWithAnalysis(options).puzzle;
}
